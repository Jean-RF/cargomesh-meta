"""Build an explicit synthetic Meta QA scenario, never a production migration."""
from pathlib import Path
import json
from uuid import UUID, uuid5

HERE = Path(__file__).resolve().parent
ORG = 'c2300000-0000-4000-8000-000000000001'
SOURCE = HERE.parent / 'v2-international-client-demo' / 'manifest.json'
old = json.loads(SOURCE.read_text(encoding='utf-8'))
namespace = UUID('6edc719b-923a-5aaf-bcfb-6a2b18f037bf')
baseline = [
    dict(id='c2330000-0000-4000-8000-000000000001', code='QA-A-LIMA', name='[SYNTHETIC] A pickup on covered lane', facilityType='SHIPPER_SITE', countryCode='PE', region=None, city='Lima', address='Synthetic Lima address', latitude=-12.05, longitude=-77.04, existing=True),
    dict(id='c2330000-0000-4000-8000-000000000002', code='QA-A-AREQUIPA', name='[SYNTHETIC] B delivery on covered lane', facilityType='WAREHOUSE', countryCode='PE', region=None, city='Arequipa', address='Synthetic Arequipa address', latitude=-16.40, longitude=-71.54, existing=True),
    dict(id='c2330000-0000-4000-8000-000000000003', code='QA-A-PIURA', name='[SYNTHETIC] Uncovered site', facilityType='SHIPPER_SITE', countryCode='PE', region=None, city='Piura', address='Synthetic Piura address', latitude=-5.19, longitude=-80.63, existing=True),
]
added = [{**f, 'sourceFacilityId': f['id'], 'id': str(uuid5(namespace, ORG + ':' + f['code'])),
          'organizationId': ORG, 'facilityType': 'WAREHOUSE', 'existing': False} for f in old['facilities']]
assert len(added) == 32
rows = [{**f, 'organizationId': ORG} for f in baseline] + added
assert len({f['id'] for f in rows}) == 35
assert len({f['countryCode'] for f in rows}) == 17
assert all(-90 <= f['latitude'] <= 90 and -180 <= f['longitude'] <= 180 for f in rows)
manifest = dict(scenario='v2-meta-international-demo', synthetic=True, localProject='meta-cr01-validation',
                organizationId=ORG, organizationCode='QA-V2-A', existingFacilities=3, addedFacilities=32,
                totalFacilities=35, totalCountries=17, coordinates='APPROXIMATE_CITY_CENTRES',
                coverageConfirmed=False, capacityConfirmed=False, offersCreated=0,
                sourceScenario=old['scenario'], facilities=rows)
(HERE / 'manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')

def lit(value):
    if value is None: return 'NULL'
    if isinstance(value, bool): return 'true' if value else 'false'
    if isinstance(value, (float, int)): return str(value)
    return "'" + value.replace("'", "''") + "'"

columns = ['id', 'code', 'name', 'facilityType', 'countryCode', 'region', 'city', 'address', 'latitude', 'longitude', 'existing']
values = ',\n'.join('(' + ','.join(lit(f[k]) for k in columns) + ')' for f in rows)
seed = f'''-- SYNTHETIC META QA SCENARIO ONLY. No production migration or automatic startup seed.
-- Target: meta-cr01-validation, QA-V2-A. Keep IDs/history and all foreign-tenant data.
-- Generated by build.py from the reviewed international catalog. City centres are approximate.
BEGIN;
SET LOCAL lock_timeout = '5s';
SELECT pg_advisory_xact_lock(hashtextextended('cargomesh:meta-international-demo:qa-v2-a',0));
DO $$ BEGIN
 IF NOT EXISTS(SELECT 1 FROM public.organizations WHERE id='{ORG}' AND code='QA-V2-A'
   AND name='[SYNTHETIC] V2 ROAD tenant A' AND status='ACTIVE') THEN
  RAISE EXCEPTION 'META_QA_ORGANIZATION_REQUIRED';
 END IF;
END $$;
CREATE TEMPORARY TABLE meta_demo_facilities(
 id uuid,code text,name text,facility_type text,country_code text,region_code text,city text,
 address_line text,latitude numeric,longitude numeric,existing boolean
) ON COMMIT DROP;
INSERT INTO meta_demo_facilities VALUES
{values};
-- Lock existing catalog rows before inspecting or filling their coordinates.
SELECT f.id FROM public.facilities f JOIN meta_demo_facilities d ON f.id=d.id FOR UPDATE OF f;
DO $$ BEGIN
 IF (SELECT count(*) FROM public.facilities f JOIN meta_demo_facilities d ON f.id=d.id AND d.existing
   WHERE f.organization_id='{ORG}' AND f.code=d.code AND f.name=d.name AND f.facility_type=d.facility_type
    AND f.country_code=d.country_code AND f.city=d.city AND f.address_line=d.address_line AND f.active)<>3 THEN
  RAISE EXCEPTION 'META_QA_BASELINE_CHANGED';
 END IF;
 IF EXISTS(SELECT 1 FROM public.facilities f JOIN meta_demo_facilities d
    ON f.id=d.id OR (f.organization_id='{ORG}' AND f.code=d.code)
   WHERE f.id<>d.id OR f.organization_id<>'{ORG}' OR f.code<>d.code OR f.name<>d.name
     OR f.facility_type<>d.facility_type OR f.country_code<>d.country_code OR f.city<>d.city
     OR f.address_line<>d.address_line OR NOT f.active
     OR (d.existing AND NOT ((f.latitude IS NULL AND f.longitude IS NULL)
       OR (f.latitude=d.latitude AND f.longitude=d.longitude)))
     OR (NOT d.existing AND (f.region_code IS DISTINCT FROM d.region_code
       OR f.latitude IS DISTINCT FROM d.latitude OR f.longitude IS DISTINCT FROM d.longitude
       OR f.access_restrictions<>'[]'::jsonb OR f.operating_hours IS NOT NULL))) THEN
  RAISE EXCEPTION 'META_FACILITY_COLLISION_REVIEW_REQUIRED';
 END IF;
END $$;
-- The existing version trigger increments only these three rows once; replay is a no-op.
UPDATE public.facilities f SET latitude=d.latitude,longitude=d.longitude
 FROM meta_demo_facilities d WHERE d.existing AND f.id=d.id AND f.organization_id='{ORG}'
 AND f.latitude IS NULL AND f.longitude IS NULL;
INSERT INTO public.facilities(id,organization_id,code,name,facility_type,country_code,region_code,city,
 address_line,latitude,longitude,active,access_restrictions,operating_hours)
 SELECT d.id,'{ORG}',d.code,d.name,d.facility_type,d.country_code,d.region_code,d.city,
 d.address_line,d.latitude,d.longitude,true,'[]'::jsonb,NULL FROM meta_demo_facilities d
 WHERE NOT d.existing AND NOT EXISTS(SELECT 1 FROM public.facilities f WHERE f.id=d.id);
DO $$ BEGIN
 IF (SELECT count(*) FROM public.facilities f JOIN meta_demo_facilities d ON f.id=d.id
   WHERE f.organization_id='{ORG}' AND f.active AND f.latitude=d.latitude AND f.longitude=d.longitude)<>35 THEN
  RAISE EXCEPTION 'INCOMPLETE_META_DEMO_CATALOG';
 END IF;
END $$;
COMMIT;
'''
(HERE / 'seed.sql').write_text(seed, encoding='utf-8')
expected = ',\n'.join('(' + ','.join([lit(f['id'])+'::uuid',lit(f['code']),lit(f['latitude']),lit(f['longitude'])]) + ')' for f in rows)
verify = f'''-- Read-only verification of the explicit Meta QA scenario.
BEGIN READ ONLY;
DO $$ DECLARE n integer; countries integer; BEGIN
 WITH expected(id,code,lat,lng) AS (VALUES
{expected})
 SELECT count(*),count(DISTINCT f.country_code) INTO n,countries FROM expected e
 JOIN public.facilities f ON f.id=e.id AND f.code=e.code
 WHERE f.organization_id='{ORG}' AND f.active AND f.latitude=e.lat AND f.longitude=e.lng;
 IF n<>35 OR countries<>17 THEN RAISE EXCEPTION 'META_DEMO_VERIFICATION_FAILED'; END IF;
END $$;
SELECT json_build_object('scenario','v2-meta-international-demo','expectedFacilities',35,
 'activeFacilities',count(*),'withCoordinates',count(*) FILTER(WHERE latitude IS NOT NULL AND longitude IS NOT NULL),
 'countries',count(DISTINCT country_code),'coverageConfirmed',false,'capacityConfirmed',false)
 FROM public.facilities WHERE organization_id='{ORG}' AND active;
COMMIT;
'''
(HERE / 'verify.sql').write_text(verify, encoding='utf-8')
print('Generated 35 synthetic Meta facilities in 17 countries; 32 additions, 3 coordinate completions.')
